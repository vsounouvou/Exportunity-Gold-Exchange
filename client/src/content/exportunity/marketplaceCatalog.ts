export function getExportunityMarketplaceCategoryItems(categorySlug: string, limit = 12) {
  const category = getExportunityParentMarketplaceCategory(categorySlug);
  if (!category) return [] as ExportunityParentCatalogItem[];

  const collected = new Map<string, ExportunityParentCatalogItem>();
  const push = (item: ExportunityParentCatalogItem | null | undefined) => {
    if (item && !collected.has(item.slug)) {
      collected.set(item.slug, item);
    }
  };

  for (const item of listExportunityParentMarketplaceItemsByCategory(categorySlug)) {
    push(item);
  }

  for (const slug of category.featuredListingSlugs || []) {
    push(getExportunityParentMarketplaceItemBySlug(slug));
  }

  for (const relatedSlug of category.relatedCategorySlugs || []) {
    for (const item of listExportunityParentMarketplaceItemsByCategory(relatedSlug)) {
      push(item);
      if (collected.size >= limit) break;
    }
    if (collected.size >= limit) break;
  }

  return Array.from(collected.values()).slice(0, limit);
}

export function getExportunityCategoryFeaturedProviders(categorySlug: string) {
  const category = getExportunityParentMarketplaceCategory(categorySlug);
  if (!category) return [] as ExportunityMarketplaceProvider[];

  const explicit = category.featuredProviders || [];
  const providers = EXPORTUNITY_MARKETPLACE_PROVIDERS.filter((provider) => {
    if (provider.categorySlugs.includes(categorySlug)) return true;
    if (!explicit.length) return false;
    return explicit.some((name) =>
      provider.providerNames.some(
        (providerName) =>
          providerName.trim().toLowerCase() === String(name).trim().toLowerCase(),
      ),
    );
  });
  return providers.slice(0, 4);
}

