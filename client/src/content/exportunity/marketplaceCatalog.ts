function slugify(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function buildSeed(
  categorySlug: string,
  providerName: string,
  sourcePlatform: string,
  sourceUrl: string,
  assignedAgentId: string,
  moduleHref: string,
  items: Array<Partial<ExportunityListingSeed> & Pick<ExportunityListingSeed, "title" | "subcategory" | "shortDescription" | "description">>,
): ExportunityListingSeed[] {
  const category = CATEGORY_LOOKUP.get(categorySlug);
  return items.map((item) => ({
    categorySlug,
    providerName: item.providerName || providerName,
    sourcePlatform: item.sourcePlatform || sourcePlatform,
    sourceUrl: item.sourceUrl || sourceUrl,
    assignedAgentId: item.assignedAgentId || assignedAgentId,
    moduleHref: item.moduleHref || moduleHref,
    imageUrl:
      item.imageUrl ||
      categoryImage[categorySlug] ||
      category?.bannerImage ||
      category?.image ||
      "/assets/exportunity/e6780893d266dc64e78172c490fc625f889e268db7469539847d3f94c7a592fc.jpg",
    currency: item.currency || "XOF",
    quoteOnly: item.quoteOnly ?? false,
    status: item.status || "active",
    ctaLabel: item.ctaLabel || (item.quoteOnly ? "Request Quote" : "View Details"),
    sourceHref: item.sourceHref ?? moduleHref,
    paymentOptions: item.paymentOptions || CATEGORY_LOOKUP.get(categorySlug)?.paymentOptions || [],
    logisticsOptions: item.logisticsOptions || CATEGORY_LOOKUP.get(categorySlug)?.logisticsOptions || [],
    compliance: item.compliance || CATEGORY_LOOKUP.get(categorySlug)?.compliance || "",
    availabilityLabel: item.availabilityLabel || (item.quoteOnly ? "Quote within 24h" : "Live in parent catalog"),
    location: item.location || "Pan-African trade desk",
    listingType: item.listingType || (categorySlug === "products" || categorySlug === "construction" || categorySlug === "machinery" || categorySlug === "gold" ? "product" : "service"),
    tags: item.tags || [sourcePlatform, categorySlug, item.subcategory],
    price: item.price ?? 0,
    title: item.title,
    subcategory: item.subcategory,
    shortDescription: item.shortDescription,
    description: item.description,
  }));
}

